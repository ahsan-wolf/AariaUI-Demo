import { EMBEDDED_PUBLIC_KEYS } from "./embedded-key.js";
/** Offline license verification (WebCrypto) and feature gating. Token format: AAIRA-<h>.<p>.<sig> (License Studio). */

export type Edition = "free" | "pro" | "enterprise";
export type Alg = "EdDSA" | "ES256" | "PS256";

export interface LicensePayload {
  v: number;
  id: string;
  customer: string;
  tier: string;
  seats: number;
  apps?: string[];
  issued: string;
  updatesUntil: string;
  /** Extra feature ids granted on top of the tier (custom bundles). Unknown ids are ignored. */
  features?: string[];
  /** Stable customer id (for support and revocation lists). */
  customerId?: string;
}

/** Feature id -> lowest edition that includes it. See docs/EDITIONS.md for the tier map. */
export const FEATURES = {
  // Free (MIT)
  "core.basic": "free",
  "styles.theme.modern": "free",
  // Pro: data controls and extra data sources (packages pro-data*, pro-extras*)
  "data.gridView": "pro",
  "data.dataList": "pro",
  "data.repeater": "pro",
  "datasource.object": "pro",
  "datasource.access": "pro",
  "datasource.xml": "pro",
  "extras.dualList": "pro",
  "styles.themes.all": "pro",
  "validation.async": "pro",
  // Enterprise (packages enterprise-*)
  "extras.sqlWhereBuilder": "enterprise",
  "security.auth": "enterprise",
  "security.sso": "enterprise",
  "security.rbac": "enterprise",
  "styles.themeBuilder": "enterprise",
  "migration.engine": "enterprise",
} as const satisfies Record<string, Edition>;
export type FeatureId = keyof typeof FEATURES;

const RANK: Record<Edition, number> = { free: 0, pro: 1, enterprise: 2 };

export function editionForTier(tier: string): Edition {
  if (tier === "enterprise") return "enterprise";
  return tier === "professional" || tier === "application" || tier === "trial" ? "pro" : "free";
}

export type Reason =
  | "none" | "malformed" | "unsupported-algorithm" | "no-public-key"
  | "bad-signature" | "expired" | "wrong-application" | "release-not-covered" | "unsigned-trial-disabled";

export interface LicenseState {
  valid: boolean;
  edition: Edition;
  reason: Reason;
  license?: LicensePayload;
  trial: boolean;
}

export class LicenseError extends Error {
  constructor(readonly feature: string, readonly required: Edition, current: Edition) {
    super(`Feature "${feature}" requires the ${required} edition (current: ${current}). Call License.activate(token).`);
    this.name = "LicenseError";
  }
}

export interface ActivateOptions {
  releaseDate?: string | Date;
  appName?: string;
  now?: Date;
}

export interface TrialOptions {
  edition?: Edition;
  days?: number;
  maxRows?: number;
  maxConditions?: number;
  maxSelectedItems?: number;
  customer?: string;
}

/** Rows shown by data controls in evaluation mode (unlicensed or trial) unless a trial sets `maxRows`. */
export const EVAL_MAX_ROWS = 10;
export const UNLICENSED_WATERMARK_TEXT = "WebForms-TS-Controls - Unlicensed: evaluation limits apply";

export const TRIAL_WATERMARK_TEXT = "WebForms-TS-Controls Trial Edition - For Evaluation Only";

/** Release date of this build; bump on each release. */
export const RELEASE_DATE = "2026-11-20";

const ALGS: Record<Alg, { imp: object; verify: object; kty: string }> = {
  EdDSA: { imp: { name: "Ed25519" }, verify: { name: "Ed25519" }, kty: "OKP" },
  ES256: { imp: { name: "ECDSA", namedCurve: "P-256" }, verify: { name: "ECDSA", hash: "SHA-256" }, kty: "EC" },
  PS256: { imp: { name: "RSA-PSS", hash: "SHA-256" }, verify: { name: "RSA-PSS", saltLength: 32 }, kty: "RSA" },
};

const b64uToBytes = (s: string): Uint8Array<ArrayBuffer> => {
  const b = s.replace(/-/g, "+").replace(/_/g, "/");
  const bin = atob(b + "=".repeat((4 - (b.length % 4)) % 4));
  const out = new Uint8Array(new ArrayBuffer(bin.length));
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
};
const day = (d: Date | string): string => (typeof d === "string" ? d : d.toISOString()).slice(0, 10);
const fail = (reason: Reason, license?: LicensePayload, trial = false): LicenseState =>
  ({ valid: false, edition: "free", reason, trial, ...(license ? { license } : {}) });

// Production public key(s) come from ./embedded-key.ts, generated by `npm run license:embed-key` (never commit a private key).

export class LicenseManager {
  private keys: JsonWebKey[] = [...EMBEDDED_PUBLIC_KEYS];
  /** Dev/test only. Production builds never accept an unsigned trial: use a signed trial token. */
  allowUnsignedTrial = false;
  private state: LicenseState = fail("none");
  private warned = new Set<string>();

  configure(o: { publicKeys: JsonWebKey[]; replace?: boolean }): void {
    this.keys = o.replace ? [...o.publicKeys] : [...this.keys, ...o.publicKeys];
  }

  /** Never throws; failures leave the free edition active. */
  async activate(token: string, o: ActivateOptions = {}): Promise<LicenseState> {
    this.warned.clear();
    return (this.state = await this.verify(token, o));
  }

  reset(): void {
    this.warned.clear();
    this.trialOptions = undefined;
    this.state = fail("none");
  }

  private trialOptions?: TrialOptions | undefined;

  get isTrial(): boolean {
    return this.state.trial;
  }

  get watermarkText(): string | undefined {
    return this.state.trial ? TRIAL_WATERMARK_TEXT : undefined;
  }

  /** Watermark for one feature: trial text, unlicensed text, or nothing when fully licensed. */
  watermarkFor(f: FeatureId): string | undefined {
    if (this.state.trial) return TRIAL_WATERMARK_TEXT;
    return this.has(f) ? undefined : UNLICENSED_WATERMARK_TEXT;
  }

  /** Row cap for data controls in trial mode (see `rowLimit()` for the per-feature answer, which includes unlicensed use). */
  get maxRows(): number | undefined {
    return this.trialOptions?.maxRows ?? (this.state.trial ? EVAL_MAX_ROWS : undefined);
  }

  /**
   * True when a paid control must run with evaluation limits: the feature is not licensed, or the license is a trial.
   * Controls use it to cap rows, disable editing and show the watermark.
   */
  evaluation(f: FeatureId): boolean {
    return this.state.trial || !this.has(f);
  }

  /** Row cap for one feature: `undefined` when fully licensed. */
  rowLimit(f: FeatureId): number | undefined {
    return this.evaluation(f) ? (this.maxRows ?? EVAL_MAX_ROWS) : undefined;
  }

  get maxConditions(): number | undefined {
    return this.trialOptions?.maxConditions ?? (this.state.trial ? 2 : undefined);
  }

  get maxSelectedItems(): number | undefined {
    return this.trialOptions?.maxSelectedItems ?? (this.state.trial ? 3 : undefined);
  }

  /**
   * Dev/test helper: an UNSIGNED trial (unlocks the edition with trial limits). Disabled by default, so a user
   * cannot unlock a paid control from the console. Enable with `License.allowUnsignedTrial = true` in demos and tests.
   * Production trials are signed tokens: `License.activate(trialToken)`.
   */
  enableTrial(o: TrialOptions = {}): LicenseState {
    if (!this.allowUnsignedTrial) return (this.state = fail("unsigned-trial-disabled"));
    this.warned.clear();
    this.trialOptions = o;
    const now = new Date();
    const days = o.days ?? 30;
    const expiry = new Date(now.getTime() + days * 86400000);
    const edition = o.edition ?? "enterprise";
    return (this.state = {
      valid: true,
      edition,
      reason: "none",
      trial: true,
      license: {
        v: 1,
        id: "TRIAL-DEMO",
        customer: o.customer ?? "Evaluation / Demo",
        tier: "trial",
        seats: 1,
        issued: day(now),
        updatesUntil: day(expiry),
      },
    });
  }

  get current(): LicenseState { return this.state; }
  get edition(): Edition { return this.state.edition; }
  has(f: FeatureId): boolean {
    if (RANK[this.state.edition] >= RANK[FEATURES[f]]) return true;
    return this.state.valid && (this.state.license?.features?.includes(f) ?? false);
  }

  assert(f: FeatureId): void {
    if (!this.has(f)) throw new LicenseError(f, FEATURES[f], this.state.edition);
  }

  /** Soft gate: false when unlicensed; warns once per feature. */
  require(f: FeatureId, onUnlicensed?: (e: LicenseError) => void): boolean {
    if (this.has(f)) return true;
    if (!this.warned.has(f)) {
      this.warned.add(f);
      const e = new LicenseError(f, FEATURES[f], this.state.edition);
      if (onUnlicensed) onUnlicensed(e); else console.warn(`[wf-controls] ${e.message}`);
    }
    return false;
  }

  async verify(token: string, o: ActivateOptions = {}): Promise<LicenseState> {
    const parts = String(token).trim().replace(/\s+/g, "").replace(/^AAIRA-/, "").split(".");
    if (!String(token).trim().startsWith("AAIRA-") || parts.length !== 3) return fail("malformed");
    const [h, p, s] = parts as [string, string, string];
    let alg: string, pl: LicensePayload, sig: Uint8Array<ArrayBuffer>;
    try {
      const dec = new TextDecoder();
      alg = (JSON.parse(dec.decode(b64uToBytes(h))) as { alg: string }).alg;
      pl = JSON.parse(dec.decode(b64uToBytes(p))) as LicensePayload;
      sig = b64uToBytes(s);
      if (typeof alg !== "string" || typeof pl.tier !== "string" || typeof pl.updatesUntil !== "string") return fail("malformed");
    } catch {
      return fail("malformed");
    }
    const spec = ALGS[alg as Alg];
    if (!spec) return fail("unsupported-algorithm");
    const subtle = globalThis.crypto?.subtle;
    const keys = this.keys.filter((k) => k.kty === spec.kty);
    if (!subtle || keys.length === 0) return fail("no-public-key");

    const data = new TextEncoder().encode(`${h}.${p}`);
    let ok = false;
    for (const jwk of keys) {
      try {
        const key = await subtle.importKey("jwk", jwk, spec.imp as never, false, ["verify"]);
        if (await subtle.verify(spec.verify as never, key, sig, data)) { ok = true; break; }
      } catch { /* next key */ }
    }
    if (!ok) return fail("bad-signature");

    const trial = pl.tier === "trial";
    if (trial && day(o.now ?? new Date()) > pl.updatesUntil) return fail("expired", pl, trial);
    if (pl.apps?.length && o.appName && !pl.apps.some((a) => a.toLowerCase() === o.appName!.toLowerCase())) {
      return fail("wrong-application", pl, trial);
    }
    // Perpetual model: a lapsed key keeps older releases working, not newer ones.
    if (!trial && day(o.releaseDate ?? RELEASE_DATE) > pl.updatesUntil) return fail("release-not-covered", pl, trial);
    return { valid: true, edition: editionForTier(pl.tier), reason: "none", license: pl, trial };
  }
}

/** Shared singleton for all paid packages. */
export const License = new LicenseManager();
export const setLicenseKey = (t: string, o?: ActivateOptions): Promise<LicenseState> => License.activate(t, o);
export const enableTrial = (o?: TrialOptions): LicenseState => License.enableTrial(o);
export const isTrial = (): boolean => License.isTrial;
export const getWatermarkText = (): string | undefined => License.watermarkText;
export const getMaxRows = (): number | undefined => License.maxRows;
export const getMaxConditions = (): number | undefined => License.maxConditions;
export const getMaxSelectedItems = (): number | undefined => License.maxSelectedItems;
export const requireFeature = (f: FeatureId, cb?: (e: LicenseError) => void): boolean => License.require(f, cb);
export const assertFeature = (f: FeatureId): void => License.assert(f);
